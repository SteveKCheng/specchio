//! Forwarding signals to the command
//!
//! Termination, hangup and user signals sent to specchio are passed on to
//! the command, and specchio keeps running (and forwarding ports) until the
//! command exits, then exits with its status.  This lets a service shut down
//! gracefully, or reload its configuration, when it's signalled through
//! specchio, by systemd (KillMode=mixed) or by a script.  See
//! notes/signals.md, section 6.
//!
//! Only signals sent from user space (kill(), sigqueue(), with si_code
//! SI_USER, SI_QUEUE, ...) are forwarded.  Those generated by the kernel
//! (SI_KERNEL) come from the terminal: Ctrl-C (SIGINT), Ctrl-\ (SIGQUIT), or
//! a hangup (SIGHUP), and the terminal sends them to its whole foreground
//! process group, the command included, so specchio ignores them, like a
//! shell waiting for a foreground job.
//!
//! Signals that were ignored when specchio started (nohup, or background
//! jobs of non-interactive shells for SIGINT and SIGQUIT) stay ignored, and
//! aren't forwarded: the command inherits them as ignored, too.
//!
//! SIGKILL can't be caught: then, the command is killed by its parent death
//! signal, as are crashes of specchio.
//!
//! The signals are blocked before the command is forked, so that none is
//! missed, and read from a signalfd in the main loop.  The command gets the
//! original signal mask back before exec().

use std::io;
use std::mem::{size_of, zeroed};
use std::os::fd::{FromRawFd, OwnedFd, RawFd};
use std::ptr;

use crate::sys::cvt;

/// Signals forwarded to the command
const FORWARD: [libc::c_int; 6] = [
    libc::SIGTERM, libc::SIGHUP, libc::SIGINT, libc::SIGQUIT, libc::SIGUSR1, libc::SIGUSR2,
];

/// Signals specchio catches, and the signal mask to restore for the command
pub struct Signals {
    set: libc::sigset_t,
    pub orig_mask: libc::sigset_t,
}

/// A signal received, from user space or not
pub struct Received {
    pub signo: libc::c_int,
    /// Sent by a process, with kill() or similar, not by the kernel
    pub user: bool,
    pub pid: u32,
}

/// Block the signals to forward, except those ignored on entry
pub fn block() -> io::Result<Signals> {
    // SAFETY: All-zero is a valid sigset_t (an empty set, on Linux)
    let (mut set, mut orig_mask): (libc::sigset_t, libc::sigset_t) = unsafe { (zeroed(), zeroed()) };
    // SAFETY: Passing pointers to valid sigset_t and sigaction structures
    unsafe {
        libc::sigemptyset(&mut set);
        for sig in FORWARD {
            let mut old: libc::sigaction = zeroed();
            cvt(libc::sigaction(sig, ptr::null(), &mut old))?;
            if old.sa_sigaction != libc::SIG_IGN {
                libc::sigaddset(&mut set, sig);
            }
        }
        // Returns an error number, not -1 with errno
        match libc::pthread_sigmask(libc::SIG_BLOCK, &set, &mut orig_mask) {
            0 => {}
            e => return Err(io::Error::from_raw_os_error(e)),
        }
    }
    Ok(Signals { set, orig_mask })
}

impl Signals {
    /// Create a non-blocking signalfd for the blocked signals
    pub fn fd(&self) -> io::Result<OwnedFd> {
        // SAFETY: Passing a pointer to a valid sigset_t
        let fd = cvt(unsafe {
            libc::signalfd(-1, &self.set, libc::SFD_NONBLOCK | libc::SFD_CLOEXEC)
        })?;
        // SAFETY: fd was just created and is owned by nobody else
        Ok(unsafe { OwnedFd::from_raw_fd(fd) })
    }
}

/// Read pending signals from signalfd @fd
pub fn read(fd: RawFd) -> Vec<Received> {
    let mut out = Vec::new();
    loop {
        // SAFETY: All-zero is a valid signalfd_siginfo
        let mut info: libc::signalfd_siginfo = unsafe { zeroed() };
        let size = size_of::<libc::signalfd_siginfo>();
        // SAFETY: Reading at most size bytes into info
        let n = unsafe { libc::read(fd, (&mut info as *mut libc::signalfd_siginfo).cast(), size) };
        if n != size as isize {
            // EAGAIN once all are read, EINTR can't happen with signals blocked
            return out;
        }
        out.push(Received {
            signo: info.ssi_signo as libc::c_int,
            // SI_USER is 0, and other codes for user space (SI_QUEUE, SI_TKILL,
            // ...) are negative, while SI_KERNEL and kernel codes are positive
            user: info.ssi_code <= 0,
            pid: info.ssi_pid,
        });
    }
}

/// Send @signo to the process referred to by @pidfd
pub fn send(pidfd: RawFd, signo: libc::c_int) -> io::Result<()> {
    // SAFETY: pidfd_send_signal() with a NULL siginfo, like kill()
    let r = unsafe {
        libc::syscall(libc::SYS_pidfd_send_signal, pidfd, signo, ptr::null::<libc::siginfo_t>(), 0)
    };
    if r < 0 { Err(io::Error::last_os_error()) } else { Ok(()) }
}

/// Name of signal @signo, for messages
pub fn name(signo: libc::c_int) -> String {
    match signo {
        libc::SIGTERM => "SIGTERM".into(),
        libc::SIGHUP => "SIGHUP".into(),
        libc::SIGINT => "SIGINT".into(),
        libc::SIGQUIT => "SIGQUIT".into(),
        libc::SIGUSR1 => "SIGUSR1".into(),
        libc::SIGUSR2 => "SIGUSR2".into(),
        n => format!("signal {n}"),
    }
}

/// Restore signal mask @mask, in the child before exec()
pub fn restore(mask: &libc::sigset_t) {
    // SAFETY: Passing a pointer to a valid sigset_t
    unsafe { libc::pthread_sigmask(libc::SIG_SETMASK, mask, ptr::null_mut()) };
}
